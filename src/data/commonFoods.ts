// ---------------------------------------------------------------------------
// A built-in list of common foods with typical nutrition, so PantryGo can
// estimate calories straight away, with no internet needed.
//
// Values are per 100 g (or per 100 ml for drinks and oils), rounded from
// standard food composition tables. Real products vary, so the app always
// shows these as estimates you can edit. A barcode scan gives the exact label.
//
// To add a food: add a line with f(...) below. Aliases are other names people
// type for it ("blue top" for whole milk).
// ---------------------------------------------------------------------------

export type CommonFood = {
  name: string;
  aliases: string[];
  basis: "g" | "ml"; // the values are per 100 of this
  kcal: number;
  protein: number;
  carbs: number;
  fat: number;
  // A typical serve, e.g. { label: "1 slice", amount: 107 } (amount in g or ml)
  portion?: { label: string; amount: number };
  // For things you count: how much one weighs (eggs, apples…), in g
  each?: number;
  // When two foods match equally: "pantry" = how it's stored (dry rice, raw chicken),
  // "meal" = how it's eaten (cooked rice). Helps pick the right one for each screen.
  prefer?: "pantry" | "meal";
  // A plated dish (pasta, curry, a burger…): offer Small / Regular / Large
  // instead of just grams, since that's how you know how much you had
  sized?: boolean;
};

type Extras = Pick<CommonFood, "portion" | "each" | "prefer" | "sized">;

// A short way to write one food:
//   f(name, aliases, basis, kcal, protein, carbs, fat, extras?)
function f(
  name: string,
  aliases: string[],
  basis: "g" | "ml",
  kcal: number,
  protein: number,
  carbs: number,
  fat: number,
  extras: Extras = {},
): CommonFood {
  return { name, aliases, basis, kcal, protein, carbs, fat, ...extras };
}

const serve = (label: string, amount: number) => ({ portion: { label, amount } });
// A dish as you'd be served it (at a café or restaurant, or a normal plate at home)
const dish = (label: string, amount: number) => ({
  portion: { label, amount },
  prefer: "meal" as const,
  sized: true,
});

